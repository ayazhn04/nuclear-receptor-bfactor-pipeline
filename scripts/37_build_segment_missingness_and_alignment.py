"""
Structural-segment alignment, Part 10 + Part 11.

Part 10: quantify feature-matrix missingness BEFORE any imputation/clustering
decision is made -- report only, propose candidate strategies, choose none.

Part 11: a SECONDARY, best-effort per-residue common-position map, built only
from the same conservative segment assignments already produced (never by
equating UniProt integers, never forced through ambiguous regions). This is
explicitly not the primary clustering input.

Reads:
    data/analysis/receptor_segment_feature_matrix_median.parquet
    data/analysis/receptor_segment_coverage_matrix.parquet
    data/analysis/receptor_segment_flexibility_profiles.parquet
    data/analysis/nr_lbd_structural_segment_map.csv
    data/manifests/nr_lbd_reference.csv

Writes:
    reports/tables/segment_feature_missingness.md
    data/analysis/nr_lbd_common_alignment_map.parquet
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

ANALYSIS = PROJECT_ROOT / "data" / "analysis"
MANIFESTS = PROJECT_ROOT / "data" / "manifests"
TABLES = PROJECT_ROOT / "reports" / "tables"

FEATURE_MATRIX_CSV = ANALYSIS / "receptor_segment_feature_matrix_median.parquet"
COVERAGE_MATRIX_CSV = ANALYSIS / "receptor_segment_coverage_matrix.parquet"
RECEPTOR_PROFILE_PARQUET = ANALYSIS / "receptor_segment_flexibility_profiles.parquet"
SEGMENT_MAP_CSV = ANALYSIS / "nr_lbd_structural_segment_map.csv"
LBD_REFERENCE_CSV = MANIFESTS / "nr_lbd_reference.csv"

MISSINGNESS_MD = TABLES / "segment_feature_missingness.md"
ALIGNMENT_MAP_PARQUET = ANALYSIS / "nr_lbd_common_alignment_map.parquet"

CANONICAL_VOCAB = (
    ["H1", "loop_H1_H2", "H2", "loop_H2_H3", "H3", "loop_H3_H4", "H4", "loop_H4_H5", "H5",
     "loop_H5_beta_sheet", "beta_sheet", "loop_beta_sheet_H6", "H6", "loop_H6_H7", "H7",
     "loop_H7_H8", "H8", "loop_H8_H9", "H9", "loop_H9_H10", "H10", "loop_H10_H11", "H11",
     "loop_H11_H12", "H12"]
)


def md_table(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    def fmt(v):
        if isinstance(v, (float, np.floating)):
            return "" if pd.isna(v) else floatfmt.format(v)
        return "" if pd.isna(v) else str(v)

    head = "| " + " | ".join(df.columns) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    body = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep] + body)


def build_missingness_report(matrix: pd.DataFrame, coverage: pd.DataFrame, rec_prof: pd.DataFrame, lbd_ref: pd.DataFrame) -> str:
    L = ["# Structural-Segment Feature-Matrix Missingness Policy Audit", "",
         "**Descriptive only. No imputation strategy is chosen here; PCA/clustering has not been run.** "
         "Generated by `scripts/37_build_segment_missingness_and_alignment.py`. Missing cells in the feature matrices "
         "are `NaN`, never `0` -- a normalized Z-score of 0 is the receptor's own mean flexibility and is a real, "
         "meaningful value, so treating a missing segment as 0 would silently and wrongly make it look average.", ""]

    L += ["## 1. STOP-CONDITION finding from Part 5 (carried forward)", "",
          "The strict topology-based labelling (Part 4/5) could confidently anchor **H1** (35/42 receptors with structural "
          "data), **H12** (39/42) and a single unambiguous **beta_sheet** region (23/42), but could NOT confidently resolve "
          "individual interior helices (H2-H11) in any of the 5 anchor receptors (VDR, PPARgamma, ESR1, GR, NR4A1) using "
          "helix-count matching alone -- real receptor-specific helix insertions/splits make the interior count deviate from "
          "the canonical topology in most receptors. Only the three closely related steroid receptors GR/MR/PR happened to "
          "match the canonical interior count exactly and got a full moderate-confidence H2-H11 labelling. **This is reported "
          "per the explicit Part 5 stop condition, not silently worked around** -- see `reports/tables/structural_segment_validation.csv` "
          "and the `evidence_notes` column of `data/analysis/nr_lbd_structural_segment_map.csv` for the per-receptor reasoning.", ""]

    n_rec, n_seg = matrix.shape[0], matrix.shape[1] - (1 if "uniprot_id" in matrix.columns else 0)
    idx = matrix.set_index("uniprot_id") if "uniprot_id" in matrix.columns else matrix
    L += ["## 2. Matrix shape and overall missingness", "",
          f"Receptor x segment median-flexibility matrix: **{n_rec} receptors x {n_seg} segment columns**.",
          f"Overall missing-cell fraction: **{idx.isna().mean().mean():.3f}**.", ""]

    total_receptors = len(lbd_ref)
    per_seg = pd.DataFrame(
        {
            "structural_segment": idx.columns,
            "receptors_represented": idx.notna().sum().values,
        }
    )
    per_seg["receptors_missing"] = total_receptors - per_seg["receptors_represented"]
    med_support = rec_prof.groupby("structural_segment")["n_pdb_entries_with_segment"].median()
    med_cov = rec_prof.groupby("structural_segment")["median_segment_coverage"].median()
    per_seg["median_pdb_support"] = per_seg["structural_segment"].map(med_support)
    per_seg["median_residue_coverage"] = per_seg["structural_segment"].map(med_cov)
    order = {s: i for i, s in enumerate(CANONICAL_VOCAB)}
    per_seg = per_seg.sort_values("structural_segment", key=lambda s: s.map(lambda x: order.get(x, 99)))
    L += ["## 3. Per-segment missingness (all 48 receptors as the denominator)", "", md_table(per_seg), ""]
    missing_names = {r: [s for s in idx.columns if pd.isna(idx.loc[r, s])] for r in idx.index if r in idx.index}

    L += ["## 4. Per-receptor segment availability", ""]
    rec_meta = rec_prof.drop_duplicates("uniprot_id")[["uniprot_id", "common_name"]].set_index("uniprot_id")["common_name"]
    per_rec = pd.DataFrame(
        {
            "uniprot_id": idx.index,
            "common_name": [rec_meta.get(u, "") for u in idx.index],
            "n_segments_available": idx.notna().sum(axis=1).values,
            "n_segments_total": n_seg,
            "fraction_available": (idx.notna().sum(axis=1) / n_seg).values,
        }
    ).sort_values("fraction_available", ascending=False)
    zero_struct = set(lbd_ref["uniprot_id"]) - set(idx.index)
    for u in sorted(zero_struct):
        row = lbd_ref[lbd_ref["uniprot_id"] == u].iloc[0]
        per_rec = pd.concat([per_rec, pd.DataFrame([{"uniprot_id": u, "common_name": row["common_name"],
                                                       "n_segments_available": 0, "n_segments_total": n_seg, "fraction_available": 0.0}])])
    L += [md_table(per_rec.reset_index(drop=True)), ""]
    L += [f"Receptors with zero structural data (no rows in the matrix at all): "
          f"{', '.join(sorted(zero_struct)) if zero_struct else 'none'}.", ""]

    L += ["## 5. Illustrative example: VDR H12", "",
          "VDR has 48 coordinate structures (all HOLO), yet the H12 segment (409-423) has a usable normalized Z-score in only "
          "**3 of those 48 PDB entries** -- in the other 45, H12 is either outside the deposited construct or its Ca positions "
          "were never observed with positive occupancy (consistent with the well-documented mobility/disorder of the AF-2 "
          "helix). This is exactly the kind of segment-specific sparsity a naive `fillna(0)` would hide.", ""]

    L += ["## 6. Candidate imputation/selection strategies (reported, none chosen)", "",
          "1. **Feature selection by support**: retain only segments observed in >= X% of receptors (e.g. H1/H12 clear "
          "the bar; most interior H-labelled segments and loops do not at X=50%).",
          "2. **Robust median imputation after feature selection**: once a segment subset is fixed, fill remaining "
          "receptor gaps with the cross-receptor median for that segment -- only defensible after (1), and must be "
          "flagged as imputed in any downstream table.",
          "3. **Iterative/KNN imputation** as a sensitivity analysis only, given how sparse and non-random the "
          "missingness is (structurally linked to construct truncation and helix mobility, not missing-at-random).",
          "4. **Algorithms tolerant of missing values** (e.g. tree-based methods) as an alternative to imputing at all.",
          "", "No strategy is selected here; this is a decision for the next (clustering) stage, informed by the "
          "per-segment/per-receptor tables above.", ""]
    return "\n".join(L)


def build_alignment_map(seg_map: pd.DataFrame) -> pd.DataFrame:
    named = seg_map[seg_map["structural_segment"] != ""].copy()
    order_index = {s: i for i, s in enumerate(CANONICAL_VOCAB)}
    named["_segment_rank"] = named["structural_segment"].map(order_index)
    named = named.sort_values(["structural_segment", "uniprot_id", "canonical_uniprot_position"])
    named["_within_rank"] = named.groupby(["uniprot_id", "structural_segment"]).cumcount()
    named["_seg_len"] = named.groupby(["uniprot_id", "structural_segment"])["canonical_uniprot_position"].transform("count")
    # A common alignment position places each segment at a fixed block, and a residue at its
    # fractional position within that block (interpolated -- explicit, never a bare UniProt integer).
    named["common_alignment_position"] = named["_segment_rank"] * 100 + np.where(
        named["_seg_len"] > 1, 100 * named["_within_rank"] / (named["_seg_len"] - 1), 0.0
    )
    out = named[["uniprot_id", "canonical_uniprot_position", "common_alignment_position", "structural_segment",
                 "assignment_status"]].reset_index(drop=True)
    return out


def main() -> None:
    matrix = pd.read_parquet(FEATURE_MATRIX_CSV)
    coverage = pd.read_parquet(COVERAGE_MATRIX_CSV)
    rec_prof = pd.read_parquet(RECEPTOR_PROFILE_PARQUET)
    lbd_ref = pd.read_csv(LBD_REFERENCE_CSV)
    seg_map = pd.read_csv(SEGMENT_MAP_CSV, keep_default_na=False)

    TABLES.mkdir(parents=True, exist_ok=True)
    MISSINGNESS_MD.write_text(build_missingness_report(matrix, coverage, rec_prof, lbd_ref) + "\n")
    print(f"Wrote {MISSINGNESS_MD.relative_to(PROJECT_ROOT)}")

    align = build_alignment_map(seg_map)
    ANALYSIS.mkdir(parents=True, exist_ok=True)
    align.to_parquet(ALIGNMENT_MAP_PARQUET, index=False)
    print(f"Wrote {ALIGNMENT_MAP_PARQUET.relative_to(PROJECT_ROOT)} ({len(align)} rows, "
          f"{align['uniprot_id'].nunique()} receptors, SECONDARY output only -- gaps left explicit, not forced)")


if __name__ == "__main__":
    main()
