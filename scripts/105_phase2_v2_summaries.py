def specificity_summary() -> list[str]:
    tiers = pd.read_csv(TABLES / "functional_site_matched_control_tiers.csv")
    mt = pd.read_csv(TABLES / "functional_site_matched_tests.csv")
    smr = pd.read_csv(TABLES / "functional_site_superfamily_matched_reanalysis.csv")
    cls = pd.read_csv(TABLES / "functional_site_interpretation_classification.csv")
    bs = pd.read_csv(TABLES / "functional_site_background_sensitivity.csv")
    dsens = pd.read_csv(TABLES / "functional_site_definition_sensitivity.csv")
    mloo = pd.read_csv(TABLES / "functional_site_matched_loo_pdb_robustness.csv")
    rchk = pd.read_csv(TABLES / "apo_holo_overlap_confidence_recheck.csv")
    fdr = pd.read_csv(TABLES / "functional_site_fdr_audit.csv")
    L = ["# Functional-site specificity validation (v2, baseline)\n", HEADER]
    L.append("## Matched background (decision S2)\n")
    L.append("Tier 1: same professor element, or for residues outside professor helices the same derived "
             "inter-element stretch (a matching device only, never a biological label). Tier 2: same independent "
             "local class from the script-34 consensus (HELIX/SHEET/COIL; unobserved positions never match). "
             "Tier 3: whole-LBD fallback. A tier needs >= 5 control positions (counted once each).\n")
    L.append("| Site | Tier 1 | Tier 2 | Tier 3 |")
    L.append("|---|---|---|---|")
    tc = tiers.groupby(["functional_site", "matched_tier_used"]).size().unstack(fill_value=0)
    for site, r in tc.iterrows():
        L.append(f"| {site} | {int(r.get('1_same_segment', 0))} | {int(r.get('2_same_class', 0))} | "
                 f"{int(r.get('3_whole_lbd_fallback', 0))} |")
    L.append(f"\nMatched tests: {len(mt)}; {int(mt['significant_within_receptor'].sum())} within-receptor FDR significant; "
             f"{int(mt['significant_global'].sum())} global.\n")
    L.append("## Confirmatory superfamily reanalysis (matched background)\n")
    L.append("Eligible definitions: legacy HIGH/MODERATE confidence or professor ground truth (decision S3; "
             "professor statuses are kept verbatim).\n")
    L.append("| Site | Receptors | Median matched delta [95% CI] | raw p | BH q | Status |")
    L.append("|---|---|---|---|---|---|")
    for _, r in smr.iterrows():
        L.append(f"| {r['functional_site']} | {int(r['n_receptors'])} | "
                 + ("n/a" if pd.isna(r["median_matched_delta"]) else
                    f"{r['median_matched_delta']:+.3f} [{r['bootstrap_ci_low']:+.3f}, {r['bootstrap_ci_high']:+.3f}]")
                 + f" | {fmt_p(r['raw_p'])} | {fmt_p(r.get('BH_q'))} | {r['status']} |")
    L.append("\n## Interpretation classification (rules of script 90)\n")
    for _, r in cls.iterrows():
        L.append(f"- **{r['functional_site']}**: {r['interpretation_category']}. {r['rationale']}")
    s3 = TABLES / f"functional_site_interpretation_classification{S3_SFX}.csv"
    if s3.exists():
        s3c = pd.read_csv(s3).set_index("functional_site")["interpretation_category"]
        s3m = pd.read_csv(TABLES / f"functional_site_superfamily_matched_reanalysis{S3_SFX}.csv").set_index("functional_site")
        changed = [s for s in cls["functional_site"] if s3c.get(s) != cls.set_index("functional_site").loc[s, "interpretation_category"]]
        L.append("\n### Sensitivity: excluding definitions that rest on professor `review_required` labels\n")
        L.append("Labelled sensitivity only; it never replaces the primary result.\n")
        for s, r in s3m.iterrows():
            L.append(f"- {s}: {int(r['n_receptors'])} receptors, status {r['status']}, "
                     + ("" if pd.isna(r["median_matched_delta"]) else f"median {r['median_matched_delta']:+.3f}, ")
                     + f"q={fmt_p(r.get('BH_q'))}; classification {s3c.get(s)}")
        L.append(f"\nClassifications changed by the sensitivity: {', '.join(changed) if changed else 'none'}.\n")
    L.append("## Background sensitivity (whole-LBD vs matched)\n")
    for site, g in bs.groupby("functional_site"):
        L.append(f"- {site}: {int(g['significant_original'].sum())} individually significant originally, "
                 f"{int(g['significance_preserved'].sum())} preserved, {int(g['significance_lost'].sum())} lost, "
                 f"{int(g['significance_gained'].sum())} gained; direction preserved in "
                 f"{g['effect_direction_preserved'].mean():.0%} of comparable results.")
    L.append("\n## Definition-quality tiers (all sites)\n")
    for _, r in dsens[dsens["functional_site"] == "ALL_SITES"].iterrows():
        L.append(f"- {r['definition_tier']}: {int(r['n_tests'])} tests in {int(r['n_receptors'])} receptors, "
                 f"{int(r['n_significant_within_fdr'])} within-FDR significant, median effect {r['median_effect_size']:+.3f}")
    L.append(f"\nMatched leave-one-PDB-out: {int((mloo['fraction_loo_p_lt_05'] == 1.0).sum())}/{len(mloo)} significant "
             "results keep p<0.05 in every fold.")
    ok = bool(fdr["q_within_matches"].all() and fdr["q_global_matches"].all())
    L.append(f"FDR recomputation audit: {'all q-values reproduce' if ok else 'MISMATCH (see functional_site_fdr_audit.csv)'}.\n")
    L.append("## Apo/holo overlap, definition level (descriptive)\n")
    for cat, n in rchk["overlap_confidence_category"].value_counts().items():
        L.append(f"- {cat}: {n}")
    L.append("")
    return L


def main() -> None:
    out = {
        "modeling_summary.md": modeling_summary(),
        "subfamily_flexibility_summary.md": subfamily_summary(),
        "apo_holo_summary.md": apo_holo_summary(),
        "current_functional_site_summary.md": functional_site_summary(),
        "functional_site_specificity_summary.md": specificity_summary(),
    }
    for name, lines in out.items():
        (TABLES / name).write_text("\n".join(lines) + "\n")
        print(f"Wrote reports/tables/{name} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
