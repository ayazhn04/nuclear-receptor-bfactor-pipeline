    sup = pd.read_csv(TABLES / "current_functional_site_superfamily_tests.csv")
    comp = pd.read_csv(TABLES / "current_functional_site_class_comparison.csv")
    lpdb = pd.read_csv(TABLES / "functional_site_loo_pdb_robustness.csv")
    lrec = pd.read_csv(TABLES / "functional_site_loo_receptor_robustness.csv")
    enr = pd.read_csv(TABLES / "atlas_functional_site_enrichment_test.csv").iloc[0]
    ovl = pd.read_csv(TABLES / "apo_holo_functional_site_overlap.csv", keep_default_na=False)
    flags = pd.read_csv(TABLES / "functional_site_confidence_coverage_flags.csv")
    L = ["# Functional-site flexibility (v2, baseline)\n", HEADER]
    L.append("Baseline results: site-vs-background contrasts are not yet controlled for solvent exposure or "
             "burial (planned SASA/burial control), so they describe where flexibility differs, not why.\n")
    L.append("## Site definitions\n")
    uniq = defs[["uniprot_id", "functional_site", "canonical_uniprot_position"]].drop_duplicates()
    L.append(f"{len(defs)} definition rows = {len(uniq)} unique (receptor, site, position) memberships plus "
             f"{len(defs) - len(uniq)} second row(s) where a position belongs to two professor elements of the same "
             f"segment-level proxy; {defs['uniprot_id'].nunique()} receptors.\n")
    L.append("| Site | Source | Level | Receptors | Unique positions |")
    L.append("|---|---|---|---|---|")
    for (site, src, lvl), g in defs.groupby(["functional_site", "definition_source", "definition_level"]):
        L.append(f"| {site} | {src} | {lvl} | {g['uniprot_id'].nunique()} | "
                 f"{g[['uniprot_id', 'canonical_uniprot_position']].drop_duplicates().shape[0]} |")
    st = avail.groupby(["functional_site", "status"]).size().unstack(fill_value=0)
    L.append("\nAvailability (coordinate receptors): " + "; ".join(
        f"{s}: " + ", ".join(f"{k} {int(v)}" for k, v in row.items() if v) for s, row in st.iterrows()) + ".\n")
    L.append("## Within-receptor tests (site vs rest of the LBD, paired by PDB entry)\n")
    L.append(f"{len(within)} tests; **{int(within['significant_within_receptor'].sum())}** significant within-receptor "
             f"FDR; {int(within['significant_global'].sum())} under the global FDR.\n")
    L.append("| Site | Tests | Within-FDR significant | Site more flexible | Site more rigid |")
    L.append("|---|---|---|---|---|")
    for site, g in within.groupby("functional_site"):
        s = g[g["significant_within_receptor"]]
        L.append(f"| {site} | {len(g)} | {len(s)} | {int((s['median_paired_delta'] > 0).sum())} | "
                 f"{int((s['median_paired_delta'] < 0).sum())} |")
    L.append("\n## Superfamily tests (one-sample Wilcoxon on receptor-level site-minus-background deltas)\n")
    L.append("| Site | Receptors | Median delta [95% CI] | raw p | FDR q | Direction |")
    L.append("|---|---|---|---|---|---|")
    for _, r in sup.iterrows():
        direction = ("more flexible than background" if r["median_delta_vs_background"] > 0 else "more rigid than background") \
            if r["significant_fdr_05"] else "no FDR-significant difference"
        L.append(f"| {r['functional_site']} | {int(r['n_receptors'])} | {r['median_delta_vs_background']:+.3f} "
                 f"[{r['bootstrap_ci_low']:+.3f}, {r['bootstrap_ci_high']:+.3f}] | {fmt_p(r['raw_p'])} | "
                 f"{fmt_p(r['fdr_q'])} | {direction} |")
    L.append("\nSite-class comparisons (paired by receptor):\n")
    for _, r in comp.iterrows():
        L.append(f"- {r['site_a']} vs {r['site_b']} (n={int(r['n_receptors_paired'])}): median difference "
                 f"{r['median_paired_difference_a_minus_b']:+.3f}, q={fmt_p(r['fdr_q'])}"
                 f"{' (FDR significant)' if r['significant_fdr_05'] else ''}")
    L.append("\n## Robustness\n")
    L.append(f"- Leave-one-PDB-out: {int((lpdb['fraction_loo_p_lt_05'] == 1.0).sum())}/{len(lpdb)} within-receptor "
             "significant results keep p<0.05 in every fold.")
    for _, r in lrec.iterrows():
        L.append(f"- Leave-one-receptor-out, {r['functional_site']}: p<0.05 in {r['fraction_loo_p_lt_05']:.0%} of folds, "
                 f"same direction in {r['fraction_loo_same_direction']:.0%}; flips: {bool(r['significance_flips_on_some_loo_fold'])}")
    L.append(f"- Definition quality: {int(flags['low_confidence_definition'].sum())}/{len(flags)} receptor x site rows rest on a "
             f"LOW/MODERATE legacy-confidence definition; {int(flags['segment_level_only'].sum())}/{len(flags)} are segment-level "
             f"proxies; {int(flags['professor_review_required'].sum())} rest on professor `review_required` labels "
             "(kept in the primary analysis; see the S3 sensitivity in the specificity summary).")
    if pd.isna(enr["fisher_p"]):
        L.append(f"- Atlas x site enrichment: not computable: {int(enr['n_site_associated'])}/{int(enr['universe_size'])} "
                 "well-supported elements are site-associated, so the 2x2 table is degenerate.")
    else:
        L.append(f"- Atlas x site enrichment: odds ratio {enr['odds_ratio']:.2f}, Fisher p={fmt_p(enr['fisher_p'])}.")
    so = ovl[(ovl["apo_holo_significant_within_receptor"] == True) & (ovl["functional_site_overlap"] == True)]  # noqa: E712
    L.append(f"- Apo/holo x site overlap: {len(so)} significant apo/holo element results overlap a site definition "
             "(descriptive; see `apo_holo_overlap_confidence_recheck.csv`).\n")
    return L


