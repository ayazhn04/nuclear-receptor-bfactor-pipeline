"""
Phase 2 report generation for the corrected v2 rerun (adaptation A24).

Replaces the legacy report scripts 54, 62, 71, 82 and 92, whose Markdown contained
v1 numbers and v1 verdicts written into the code. Every number, receptor name,
significant finding and verdict below is read from the current result tables; a
sentence that depends on a result is emitted only when the table supports it, and
every verdict states the rule that produced it. The claim lines checked by the
unchanged script 95 keep their legacy wording.

Also writes reports/tables/modeling_imputed_cells.csv: every imputed cell of the
primary modeling matrix with the exact reason it is missing (missing != 0; an
imputed value is a modeling placeholder, never an observed measurement).

Runs inside the Phase 2 sandbox (scripts/104), after the last result table.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[1]
ANALYSIS = PROJECT_ROOT / "data" / "analysis"
TABLES = PROJECT_ROOT / "reports" / "tables"
S3_SFX = "_sensitivity_excl_review_required"

# Reporting conventions (descriptive, fixed before reading any v2 result)
SILHOUETTE_BANDS = [(0.70, "strong structure"), (0.51, "reasonable structure"),
                    (0.26, "weak structure"), (-1.0, "no substantial structure")]  # Kaufman & Rousseeuw 1990
STRONG_ARI = 0.70  # cross-method agreement called "strong" above this (legacy wording)
ALPHA = 0.05

HEADER = ("> Corrected v2 rerun (professor canonical elements, corrected residue numbering, final "
          "analysis span). Generated by `scripts/105_phase2_v2_summaries.py` from the result tables "
          "only; no number or verdict is written into the code.\n")


def silhouette_band(s: float) -> str:
    return next(label for cut, label in SILHOUETTE_BANDS if s >= cut)


def fmt_p(p) -> str:
    return "n/a" if pd.isna(p) else (f"{p:.2e}" if p < 1e-3 else f"{p:.4f}")


def names(rows, col="nr_code") -> str:
    return ", ".join(rows[col].astype(str)) if len(rows) else "none"


def common_names() -> dict:
    rfs = pd.read_csv(ANALYSIS / "receptor_flexibility_summary.csv")
    return dict(zip(rfs["uniprot_id"], rfs["common_name"]))


