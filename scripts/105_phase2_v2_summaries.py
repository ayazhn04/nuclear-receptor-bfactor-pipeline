def subfamily_summary() -> list[str]:
    kw = pd.read_csv(TABLES / "subfamily_segment_kruskal.csv")
    kw_mean = pd.read_csv(TABLES / "subfamily_segment_kruskal_mean_sensitivity.csv")
    post = pd.read_csv(TABLES / "subfamily_segment_posthoc.csv")
    loo = pd.read_csv(TABLES / "subfamily_kruskal_loo_robustness.csv")
    atlas = pd.read_csv(ANALYSIS / "superfamily_segment_flexibility_atlas.csv")
    aloo = pd.read_csv(TABLES / "subfamily_atlas_loo_robustness.csv")
    L = ["# Subfamily tests and superfamily atlas (v2)\n", HEADER]
    L.append("## Group tests (Kruskal-Wallis per element; BH-FDR within each grouping scheme)\n")
    for scheme, g in kw.groupby("grouping_scheme", sort=False):
        t = g[g["test_status"] == "TESTED"]
        nsig = int((t["significant_fdr_05"] == True).sum())  # noqa: E712
        tag = "PRIMARY" if scheme == "primary_project_group" else "SECONDARY"
        L.append(f"- `{scheme}`: {len(t)} elements tested; nominal p<0.05: {int((t['raw_p'] < ALPHA).sum())}; "
                 f"FDR significant segments: {nsig} ({tag})"
                 + (f" -> {', '.join(t.loc[t['significant_fdr_05'] == True, 'structural_segment'])}" if nsig else "")  # noqa: E712
                 )
    L.append("")
    L.append("| Scheme | Element | n receptors | H | raw p | FDR q | epsilon^2 [95% CI] |")
    L.append("|---|---|---|---|---|---|---|")
    for _, r in kw[kw["test_status"] == "TESTED"].sort_values(["grouping_scheme", "raw_p"]).iterrows():
        L.append(f"| {r['grouping_scheme']} | {r['structural_segment']} | {int(r['n_receptors'])} | "
                 f"{r['H_statistic']:.2f} | {fmt_p(r['raw_p'])} | {fmt_p(r['fdr_q'])} | "
                 f"{r['epsilon_squared']:.3f} [{r['epsilon_squared_ci_low']:.3f}, {r['epsilon_squared_ci_high']:.3f}] |")
    L.append(f"\nPost-hoc pairwise tests (run only for FDR-significant omnibus results): {len(post)} rows.\n")
    L.append("### Robustness\n")
    for _, r in loo.iterrows():
        L.append(f"- leave-one-receptor-out, {r['grouping_scheme']} {r['structural_segment']} (raw p "
                 f"{fmt_p(r['full_raw_p'])}): p<0.05 kept in {r['fraction_loo_still_p_lt_05']:.0%} of folds; "
                 f"depends on a single receptor: {bool(r['conclusion_depends_on_single_receptor'])}")
    msig = kw_mean[(kw_mean["test_status"] == "TESTED") & (kw_mean["significant_fdr_05"] == True)]  # noqa: E712
    L.append(f"- mean-instead-of-median sensitivity: FDR-significant in {len(msig)} scheme x element tests"
             + (": " + ", ".join(f"{a} {b}" for a, b in zip(msig["grouping_scheme"], msig["structural_segment"]))
                if len(msig) else "") + ". This is a sensitivity result, not the primary analysis.\n")

    L.append("## Superfamily element atlas (descriptive)\n")
    well = atlas[atlas["well_supported"]].sort_values("median_receptor_z", ascending=False)
    L.append(f"{len(atlas)} professor elements; {len(well)} well supported (>= 10 receptors). Values are medians "
             "of receptor-level element medians of per-instance B-factor z-scores; z is relative to each "
             "instance's whole analysis span, which also contains the inter-helix regions not shown here.\n")
    L.append("| Rank (well supported) | Element | n receptors | median z [95% CI] | fraction > 0 |")
    L.append("|---|---|---|---|---|")
    for i, (_, r) in enumerate(well.iterrows(), 1):
        L.append(f"| {i} | {r['structural_segment']} | {int(r['n_receptors'])} | {r['median_receptor_z']:+.3f} "
                 f"[{r['bootstrap_95ci_median_low']:+.3f}, {r['bootstrap_95ci_median_high']:+.3f}] | "
                 f"{r['fraction_receptors_above_0']:.2f} |")
    L.append(f"\nMost flexible well-supported element: {well.iloc[0]['structural_segment']}; most rigid: "
             f"{well.iloc[-1]['structural_segment']}. Elements with < 10 receptors (descriptive only): "
             + ", ".join(f"{r['structural_segment']} (n={int(r['n_receptors'])})"
                         for _, r in atlas[~atlas["well_supported"]].iterrows()) + ".")
    dom = aloo[aloo["dominated_by_single_receptor"] == True]  # noqa: E712
    L.append(f"\nAtlas leave-one-receptor-out: elements dominated by a single receptor: {names(dom, 'structural_segment')}.\n")
    return L


