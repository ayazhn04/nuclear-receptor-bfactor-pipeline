def apo_holo_summary() -> list[str]:
    elig = pd.read_csv(TABLES / "apo_holo_receptor_eligibility.csv")
    seg = pd.read_csv(TABLES / "apo_holo_segment_tests.csv")
    rsum = pd.read_csv(TABLES / "apo_holo_receptor_summary.csv")
    res = pd.read_parquet(ANALYSIS / "apo_holo_residue_effects.parquet")
    loo = pd.read_csv(TABLES / "apo_holo_loo_robustness.csv")
    qc = pd.read_csv(TABLES / "apo_holo_qc_balance.csv")
    cn = common_names()
    L = ["# APO vs HOLO (v2)\n", HEADER]
    L.append("Associations between ligand state and element flexibility across PDB entries; **not causal "
             "ligand effects** (ligand chemistry, constructs, mutations, crystal contacts and resolution are not "
             "controlled).\n")
    L.append("## Scope (decision S1)\n")
    ex = elig[elig["n_excluded_TRACE_LBD"] > 0]
    L.append("Entries whose every coordinate candidate is a trace LBD fragment (`TRACE_LBD`, receptor peptides "
             "bound to other proteins) are kept in the master data but excluded from APO and HOLO alike. "
             f"Excluded entries entering the counts: {int(elig['n_excluded_TRACE_LBD'].sum())} ("
             + ", ".join(f"{cn.get(r['uniprot_id'])} {int(r['n_excluded_TRACE_LBD'])}" for _, r in ex.iterrows())
             + ").\n")
    n_p, n_e = int(elig["eligible_primary_5_5"].sum()), int(elig["eligible_exploratory_3_3"].sum())
    L.append(f"- PRIMARY (>=5 APO and >=5 HOLO PDB entries): {n_p}/{len(elig)} receptors eligible: "
             + names(elig[elig["eligible_primary_5_5"]].assign(n=lambda d: d["uniprot_id"].map(cn)), "n"))
    L.append(f"- EXPLORATORY (>=3/>=3): {n_e}/{len(elig)} eligible (adds "
             + names(elig[elig["eligible_exploratory_3_3"] & ~elig["eligible_primary_5_5"]]
                     .assign(n=lambda d: d["uniprot_id"].map(cn)), "n") + ")")
    for uid in ["P04150", "P11473"]:
        r = elig[elig["uniprot_id"] == uid]
        if len(r):
            r = r.iloc[0]
            L.append(f"- {cn.get(uid)}: {int(r['n_APO'])} APO / {int(r['n_HOLO'])} HOLO usable "
                     f"({int(r['n_excluded_TRACE_LBD'])} TRACE_LBD excluded, {int(r['n_NOT_ASSESSABLE'])} not "
                     f"normalizable): {'eligible' if r['eligible_exploratory_3_3'] else 'not testable'}.")
    L.append("- GR was already ineligible under the usable-data rule; S1 additionally ensures peptide fragments "
             "cannot enter an LBD comparison.\n")
    L.append("## Element tests (Mann-Whitney per receptor x element)\n")
    L.append(f"{len(seg)} tests in {seg['uniprot_id'].nunique()} receptors. **{int(seg['significant_within_receptor'].sum())}** "
             f"significant within-receptor FDR (primary family); **{int(seg['significant_global'].sum())}** significant "
             "under the SECONDARY global FDR.\n")
    sig = seg[seg["significant_within_receptor"]].sort_values(["nr_code", "raw_p"])
    if len(sig):
        L.append("| Receptor | Element | Tier | APO n | HOLO n | delta median z (HOLO-APO) | Cliff's delta | raw p | q within | LOO p<0.05 | QC imbalance |")
        L.append("|---|---|---|---|---|---|---|---|---|---|---|")
        for _, r in sig.iterrows():
            lr = loo[(loo["uniprot_id"] == r["uniprot_id"]) & (loo["structural_segment"] == r["structural_segment"])]
            qf = qc[qc["uniprot_id"] == r["uniprot_id"]]
            loo_txt = f"{lr.iloc[0]['fraction_loo_p_lt_05']:.0%}" if len(lr) else "n/a"
            L.append(f"| {cn.get(r['uniprot_id'])} | {r['structural_segment']} | {r['eligibility_tier']} | "
                     f"{int(r['apo_n'])} | {int(r['holo_n'])} | {r['delta_median_z']:+.3f} | {r['cliffs_delta']:+.2f} | "
                     f"{fmt_p(r['raw_p'])} | {fmt_p(r['q_within_receptor'])} | {loo_txt} | "
                     f"{bool(qf.iloc[0]['qc_imbalance_flagged']) if len(qf) else 'n/a'} |")
    L.append("\nPer receptor:\n")
    for _, r in rsum.iterrows():
        L.append(f"- {cn.get(r['uniprot_id'])}: {int(r['n_tested_segments'])} elements, "
                 f"{int(r['n_significant_within_receptor_fdr'])} within-FDR significant; median delta "
                 f"{r['median_delta_across_segments']:+.3f}")
    flagged = qc[qc["qc_imbalance_flagged"]]
    L.append(f"\nAPO/HOLO QC imbalance (resolution, R-free or coverage differ at p<0.05): "
             f"{', '.join(cn.get(u) for u in flagged['uniprot_id']) or 'none'}. Results in these receptors carry that caveat.\n")
    L.append("## Residue-level tests (exploratory)\n")
    rs = res[res["significant_within_receptor"]]
    L.append(f"{len(res)} position tests; {len(rs)} within-receptor FDR significant in "
             f"{rs['uniprot_id'].nunique()} receptors ("
             + ", ".join(f"{cn.get(u)} {n}" for u, n in rs.groupby("uniprot_id").size().items()) + "). "
             "Positions inside two professor elements carry a joined display label (e.g. `H3|H4`); it is not an element. "
             "Positions between professor helices carry no element label.\n")
    return L


