def imputed_cells() -> pd.DataFrame:
    mask = pd.read_parquet(ANALYSIS / "receptor_segment_matrix_primary_imputation_mask.parquet").set_index("uniprot_id")
    seg = pd.read_csv(ANALYSIS / "nr_lbd_structural_segment_map.csv", keep_default_na=False)
    defined = seg[seg["structural_segment"] != ""].groupby("uniprot_id")["structural_segment"].agg(set).to_dict()
    cn = common_names()
    rows = []
    for uid, r in mask.iterrows():
        for feat, imp in r.items():
            if not imp:
                continue
            reason = ("PROFESSOR_ELEMENT_NOT_DEFINED_FOR_RECEPTOR" if feat not in defined.get(uid, set())
                      else "ELEMENT_DEFINED_BUT_NO_OBSERVED_DATA")
            rows.append({"uniprot_id": uid, "receptor": cn.get(uid, uid), "feature": feat, "missing_reason": reason,
                         "nomenclature_driven": reason == "PROFESSOR_ELEMENT_NOT_DEFINED_FOR_RECEPTOR" and feat == "H10/H11"
                         and {"H10", "H11"} <= defined.get(uid, set()),
                         "imputation_rule": "per-feature cohort median (primary); KNN, mean-matrix and complete-case as sensitivity",
                         "value_status": "IMPUTED_PLACEHOLDER_NOT_AN_OBSERVATION"})
    return pd.DataFrame(rows, columns=["uniprot_id", "receptor", "feature", "missing_reason", "nomenclature_driven",
                                       "imputation_rule", "value_status"])


def modeling_summary() -> list[str]:
    audit = pd.read_csv(TABLES / "modeling_feature_support.csv")
    cohort = pd.read_csv(ANALYSIS / "modeling_receptor_cohort.csv")
    cs = json.loads((ANALYSIS / "modeling_cohort_matrix_summary.json").read_text())
    pv = pd.read_csv(TABLES / "pca_variance.csv")
    ps = json.loads((ANALYSIS / "pca_summary.json").read_text())
    load = pd.read_csv(ANALYSIS / "pca_loadings.csv").set_index("structural_segment")
    us = json.loads((ANALYSIS / "umap_stability_summary.json").read_text())
    val = pd.read_csv(TABLES / "clustering_validation.csv")
    agr = pd.read_csv(TABLES / "clustering_method_agreement.csv")
    db = pd.read_csv(TABLES / "clustering_dbscan_grid.csv")
    sens = pd.read_csv(TABLES / "clustering_sensitivity.csv")
    clus = json.loads((ANALYSIS / "clustering_summary.json").read_text())
    over = pd.read_csv(TABLES / "entry_level_overrepresentation.csv")
    seg = pd.read_csv(ANALYSIS / "nr_lbd_structural_segment_map.csv", keep_default_na=False)
    mapped = set(seg.loc[seg["structural_class"] != "NO_PROFESSOR_MAPPING", "uniprot_id"])
    cn = common_names()

    imp = imputed_cells()
    imp.to_csv(TABLES / "modeling_imputed_cells.csv", index=False)

    feats = cs["primary_features"]
    inc, exc = cohort[cohort["included_primary"]], cohort[~cohort["included_primary"]]
    n_cells = len(inc) * len(feats)
    L = ["# Modeling summary (v2)\n", HEADER]
    L.append("## Feature support\n")
    L.append(f"Elements audited: {len(audit)} (professor element vocabulary). Rule: a feature enters the "
             f"primary matrix when observed in >= {cs['primary_support_threshold']:.0%} of the "
             f"{int(audit['n_coordinate_receptors_total'].iloc[0])} coordinate receptors.\n")
    L.append("| Element | Receptors with a value | Fraction | In primary matrix |")
    L.append("|---|---|---|---|")
    for _, r in audit.sort_values(["fraction_supported", "structural_segment"], ascending=[False, True]).iterrows():
        L.append(f"| {r['structural_segment']} | {int(r['n_coordinate_receptors_supported'])}/"
                 f"{int(r['n_coordinate_receptors_total'])} | {r['fraction_supported']:.3f} | "
                 f"{'yes' if r['structural_segment'] in feats else 'no'} |")
    L.append(f"\nPrimary features ({len(feats)}): {', '.join(feats)}.\n")

    L.append("## Cohort\n")
    L.append(f"Rule: a receptor enters when >= {cs['cohort_observed_fraction_rule']:.0%} of the primary features are "
             f"observed. **{len(inc)}/{len(cohort)}** coordinate receptors included.\n")
    for _, r in exc.iterrows():
        why = ("no professor canonical mapping, so no element features"
               if r["uniprot_id"] not in mapped else f"observed fraction {r['observed_fraction']:.2f}")
        L.append(f"- excluded: {cn.get(r['uniprot_id'], r['uniprot_id'])} ({r['nr_code']}), "
                 f"{int(r['n_observed_features'])}/{int(r['n_selected_features'])} features observed: {why}")
    L.append("")

    L.append("## Missing values and imputation\n")
    by_reason = imp["missing_reason"].value_counts().to_dict()
    L.append(f"Missing before imputation: **{len(imp)}/{n_cells}** cells ({len(imp) / n_cells:.1%}). By reason: "
             + "; ".join(f"{k}: {v}" for k, v in by_reason.items())
             + f". Nomenclature-driven (separate professor H10 and H11, no combined H10/H11): "
               f"{int(imp['nomenclature_driven'].sum())}.\n")
    L.append("Imputed values are modeling placeholders used only where an algorithm needs a complete matrix; "
             "the element profile tables keep these cells missing (NaN, never 0). Every cell is listed in "
             "`reports/tables/modeling_imputed_cells.csv`.\n")
    if len(imp):
        L.append("| Receptor | Feature | Reason |")
        L.append("|---|---|---|")
        for _, r in imp.sort_values(["feature", "receptor"]).iterrows():
            L.append(f"| {r['receptor']} | {r['feature']} | {r['missing_reason']} |")
    L.append(f"\nComplete-case sensitivity: {cs['n_complete_case_receptors']} fully observed receptors "
             f"({cs['complete_case_status']}).\n")

    L.append("## PCA\n")
    pc1 = pv.iloc[0]["explained_variance_ratio"]
    L.append(f"{ps['n_samples']} receptors x {ps['n_features']} features (scaled). PC1 explains "
             f"{pc1:.1%} of the variance, PC2 {pv.iloc[1]['explained_variance_ratio']:.1%}. Components needed: "
             + ", ".join(f"{k}: {v}" for k, v in ps["n_components_for_variance"].items()) + ".\n")
    for pc in ["PC1", "PC2"]:
        top = load[pc].abs().sort_values(ascending=False).head(3)
        L.append(f"- {pc} largest |loadings|: " + ", ".join(f"{s} ({load.loc[s, pc]:+.2f})" for s in top.index))
    L.append("")

    L.append("## UMAP\n")
    L.append(f"Visualization only. Stability across n_neighbors {us['n_neighbors_grid']}, min_dist "
             f"{us['min_dist_grid']}, seeds {us['seeds']}: mean Spearman correlation to the reference "
             f"embedding {us['overall_mean_spearman_to_reference']:.3f}; script 51 rule: {us['verdict']}.\n")

    L.append("## Clustering battery and validation\n")
    pp = val[val["input"] == "pca_primary"].dropna(subset=["silhouette"])
    best = pp.sort_values("silhouette", ascending=False).iloc[0]
    db_max = int(db[db["input"] == "pca_primary"]["n_clusters_found"].max())
    ari_k = agr[agr["input"] == "pca_primary"].groupby("k")["adjusted_rand_index"].mean()
    L.append(f"- Best single solution (PCA-primary, {len(pp)} method x k fits): `{best['method']}`, "
             f"k={int(best['k'])}, silhouette={best['silhouette']:.3f} "
             f"(Davies-Bouldin={best['davies_bouldin']:.3f}, Calinski-Harabasz={best['calinski_harabasz']:.2f}); "
             f"band: {silhouette_band(best['silhouette'])}.")
    L.append(f"- Silhouette over the whole PCA-primary battery: max {pp['silhouette'].max():.3f}, "
             f"median {pp['silhouette'].median():.3f}, min {pp['silhouette'].min():.3f}.")
    L.append("- Gap statistic chosen k: " + ", ".join(f"{k}={v}" for k, v in clus["gap_chosen_k"].items())
             + f" (k tested {min(clus['k_range'])}-{max(clus['k_range'])}).")
    L.append(f"- DBSCAN (full eps x min_samples grid, PCA-primary): maximum number of clusters found **{db_max}**.")
    L.append(f"- Cross-method agreement (mean ARI across method pairs, PCA-primary): {ari_k.min():.3f} "
             f"(k={ari_k.idxmin()}) to {ari_k.max():.3f} (k={ari_k.idxmax()}).\n")
    L.append("### Sensitivity (imputation and input matrix)\n")
    L.append("| Comparison (K-means at matched k) | Mean ARI | Min | Max |")
    L.append("|---|---|---|---|")
    for comp, g in sens.groupby("comparison"):
        L.append(f"| {comp} | {g['adjusted_rand_index'].mean():.3f} | {g['adjusted_rand_index'].min():.3f} | "
                 f"{g['adjusted_rand_index'].max():.3f} |")
    L.append("\n| Input | Best silhouette | DBSCAN max clusters | Gap k |")
    L.append("|---|---|---|---|")
    for inp, g in val.dropna(subset=["silhouette"]).groupby("input"):
        L.append(f"| {inp} | {g['silhouette'].max():.3f} | "
                 f"{int(db[db['input'] == inp]['n_clusters_found'].max()) if (db['input'] == inp).any() else 'n/a'} | "
                 f"{clus['gap_chosen_k'].get(inp, 'n/a')} |")
    L.append("")

    L.append("## Discrete clusters vs continuum (rule-based)\n")
    crit = {
        f"best silhouette >= 0.51 (reasonable structure or better)": best["silhouette"] >= 0.51,
        "DBSCAN finds >= 2 clusters somewhere on the grid (PCA-primary)": db_max >= 2,
        "gap statistic picks a k above the smallest tested (PCA-primary)":
            clus["gap_chosen_k"].get("pca_primary", min(clus["k_range"])) > min(clus["k_range"]),
        f"mean cross-method ARI > {STRONG_ARI} at some k (PCA-primary)": bool((ari_k > STRONG_ARI).any()),
    }
    L.append("| Criterion | Met |")
    L.append("|---|---|")
    for c, ok in crit.items():
        L.append(f"| {c} | {'yes' if ok else 'no'} |")
    n_met = sum(crit.values())
    if n_met == len(crit):
        verdict = "all criteria met: the data support a discrete cluster structure at this sample size"
    elif n_met == 0:
        verdict = ("no criterion met: the v2 data do **not** support a robust discrete cluster structure; this is "
                   "consistent with, but does not prove, a continuum of element-level flexibility profiles")
    else:
        verdict = (f"{n_met}/{len(crit)} criteria met: evidence for discrete clusters is weak or inconsistent; no "
                   "cluster solution is adopted")
    L.append(f"\n**Verdict ({n_met}/{len(crit)} criteria):** {verdict}.\n")

    L.append("## Group labels and entry-level view\n")
    top5 = over.sort_values("n_pdb_entries", ascending=False)["n_pdb_entries"].head(5).sum() / over["n_pdb_entries"].sum()
    L.append("Group labels were used only for figure overlays, never as model inputs. Entry-level view "
             f"(secondary): PDB entries per receptor range {int(over['n_pdb_entries'].min())}-"
             f"{int(over['n_pdb_entries'].max())}; the 5 most represented receptors hold {top5:.1%} of entries, "
             "which is why the receptor-level matrix is primary.\n")
    L.append("## Limitations\n")
    L.append(f"- {len(inc)} receptors and {len(feats)} features: limited power for any clustering method.")
    L.append("- Features are professor-defined helices only; inter-helix regions are not modeled as features.")
    L.append("- Imputed cells reflect elements the professor table does not define for that receptor; they are "
             "placeholders, not measurements (see the imputation section).")
    return L


