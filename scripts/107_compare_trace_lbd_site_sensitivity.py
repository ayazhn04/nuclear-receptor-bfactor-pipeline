"""
Labelled sensitivity: functional-site analyses (scripts 72-91) without TRACE_LBD-only
receptor x PDB entries (receptor fragments/peptides), versus the primary v2 analysis
that keeps them. Produced by `scripts/104_run_phase2_sandbox.py --trace-sensitivity`.

Writes reports/rebuild_v2/trace_lbd_site_sensitivity.md and
reports/rebuild_v2/tables/trace_lbd_site_sensitivity_comparison.csv.
The primary analysis is not changed by this script.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from scripts.utils import apo_holo_scope  # noqa: E402

V2A = PROJECT_ROOT / "data" / "rebuild_v2" / "analysis"
V2T = PROJECT_ROOT / "reports" / "rebuild_v2" / "tables"
SENS = V2T / "trace_lbd_site_sensitivity"
SANDBOX = PROJECT_ROOT / "data" / "interim" / "rebuild_v2"
KEY = ["uniprot_id", "functional_site"]


def load(name: str, sens: bool) -> pd.DataFrame:
    root = SENS if sens else (V2A if name.endswith(".parquet") else V2T)
    if not sens and name.endswith(".parquet") and not (root / name).exists():
        root = V2A
    return pd.read_parquet(root / name) if name.endswith(".parquet") else pd.read_csv(root / name)


def main() -> None:
    trace = apo_holo_scope.trace_lbd_entries(SANDBOX)
    rows, L = [], ["# TRACE_LBD functional-site sensitivity (v2)\n",
                   "> Labelled sensitivity. Primary v2 site analyses keep TRACE_LBD-only entries (receptor "
                   "fragments bound to other proteins); this run removes them from pocket-contact geometry "
                   "(72), site flexibility (74) and matched background (85) and re-runs 72-91 unchanged "
                   "otherwise. Generated by `scripts/107_compare_trace_lbd_site_sensitivity.py`.\n"]

    # 1. which entries contribute, to which sites
    contrib = []
    for name, sites in [("pdb_functional_site_flexibility.parquet", True),
                        ("pdb_functional_site_matched_background.parquet", True),
                        ("ligand_pocket_raw_contacts.parquet", False)]:
        d = pd.read_parquet(V2A / name)
        d = d[[(u, p) in trace for u, p in zip(d["uniprot_id"], d["pdb_id"])]]
        for (u, p), g in d.groupby(["uniprot_id", "pdb_id"]):
            contrib.append({"table": name, "uniprot_id": u, "pdb_id": p,
                            "sites": ";".join(sorted(g["functional_site"].unique())) if sites else "pocket contacts",
                            "rows": len(g)})
    contrib = pd.DataFrame(contrib)
    L.append("## Contributing TRACE_LBD entries (primary analysis)\n")
    L.append("| Table | Receptor | PDB | Sites | Rows |")
    L.append("|---|---|---|---|---|")
    for _, r in contrib.iterrows():
        L.append(f"| {r['table']} | {r['uniprot_id']} | {r['pdb_id']} | {r['sites']} | {r['rows']} |")

    # 2. definitions (pocket consensus)
    d1, d2 = load("current_functional_site_definitions.parquet", False), load("current_functional_site_definitions.parquet", True)
    k = ["uniprot_id", "functional_site", "canonical_uniprot_position"]
    s1, s2 = set(map(tuple, d1[k].values)), set(map(tuple, d2[k].values))
    def_changed = sorted({(u, s) for u, s, _ in s1 ^ s2})
    rows.append({"quantity": "site-definition memberships changed", "primary": len(s1), "sensitivity": len(s2),
                 "changed": len(s1 ^ s2), "detail": "; ".join(f"{u} {s}" for u, s in def_changed)})

    # 3. within-receptor tests
    w1 = load("current_functional_site_within_receptor_tests.csv", False).set_index(KEY)
    w2 = load("current_functional_site_within_receptor_tests.csv", True).set_index(KEY)
    common = w1.index.intersection(w2.index)
    affected = sorted(set(w1.index) ^ set(w2.index) | {i for i in common if
                      (w1.loc[i, "n_pairs"] != w2.loc[i, "n_pairs"]) or abs(w1.loc[i, "raw_p"] - w2.loc[i, "raw_p"]) > 0})
    flips = [i for i in common if w1.loc[i, "significant_within_receptor"] != w2.loc[i, "significant_within_receptor"]]
    rows.append({"quantity": "within-receptor tests", "primary": len(w1), "sensitivity": len(w2),
                 "changed": len(affected), "detail": "affected: " + "; ".join(f"{u} {s}" for u, s in affected)})
    rows.append({"quantity": "within-receptor FDR significant", "primary": int(w1["significant_within_receptor"].sum()),
                 "sensitivity": int(w2["significant_within_receptor"].sum()), "changed": len(flips),
                 "detail": "significance flips: " + ("; ".join(f"{u} {s}" for u, s in flips) or "none")})
    # 4. superfamily
    f1 = load("current_functional_site_superfamily_tests.csv", False).set_index("functional_site")
    f2 = load("current_functional_site_superfamily_tests.csv", True).set_index("functional_site")
    for s in f1.index:
        rows.append({"quantity": f"superfamily {s} median delta (q)",
                     "primary": f"{f1.loc[s, 'median_delta_vs_background']:+.3f} ({f1.loc[s, 'fdr_q']:.2e})",
                     "sensitivity": f"{f2.loc[s, 'median_delta_vs_background']:+.3f} ({f2.loc[s, 'fdr_q']:.2e})",
                     "changed": int(bool(f1.loc[s, "significant_fdr_05"]) != bool(f2.loc[s, "significant_fdr_05"])
                                    or (f1.loc[s, "median_delta_vs_background"] > 0) != (f2.loc[s, "median_delta_vs_background"] > 0)),
                     "detail": f"n receptors {int(f1.loc[s, 'n_receptors'])} -> {int(f2.loc[s, 'n_receptors'])}"})
    # 5. matched background and classification
    m1 = load("functional_site_matched_tests.csv", False).set_index(KEY)
    m2 = load("functional_site_matched_tests.csv", True).set_index(KEY)
    mflips = [i for i in m1.index.intersection(m2.index)
              if m1.loc[i, "significant_within_receptor"] != m2.loc[i, "significant_within_receptor"]]
    rows.append({"quantity": "matched-background FDR significant", "primary": int(m1["significant_within_receptor"].sum()),
                 "sensitivity": int(m2["significant_within_receptor"].sum()), "changed": len(mflips),
                 "detail": "flips: " + ("; ".join(f"{u} {s}" for u, s in mflips) or "none")})
    c1 = load("functional_site_interpretation_classification.csv", False).set_index("functional_site")["interpretation_category"]
    c2 = load("functional_site_interpretation_classification.csv", True).set_index("functional_site")["interpretation_category"]
    for s in c1.index:
        rows.append({"quantity": f"classification {s}", "primary": c1[s], "sensitivity": c2.get(s, ""),
                     "changed": int(c1[s] != c2.get(s)), "detail": ""})
    r1 = load("functional_site_superfamily_matched_reanalysis.csv", False).set_index("functional_site")
    r2 = load("functional_site_superfamily_matched_reanalysis.csv", True).set_index("functional_site")
    for s in r1.index:
        a, b = r1.loc[s, "median_matched_delta"], r2.loc[s, "median_matched_delta"]
        rows.append({"quantity": f"matched superfamily {s} median delta", "primary": "n/a" if pd.isna(a) else f"{a:+.3f}",
                     "sensitivity": "n/a" if pd.isna(b) else f"{b:+.3f}",
                     "changed": int(r1.loc[s, "status"] != r2.loc[s, "status"] or
                                    bool(r1.loc[s, "significant_fdr_05"] == True) != bool(r2.loc[s, "significant_fdr_05"] == True)),  # noqa: E712
                     "detail": f"status {r1.loc[s, 'status']} -> {r2.loc[s, 'status']}"})
    comp = pd.DataFrame(rows)
    comp.to_csv(V2T / "trace_lbd_site_sensitivity_comparison.csv", index=False)

    material = int(comp.loc[comp["quantity"].str.startswith(("classification", "superfamily", "matched superfamily")), "changed"].sum())
    L.append("\n## Primary vs sensitivity\n")
    L.append("| Quantity | Primary | Without TRACE_LBD | Changed | Detail |")
    L.append("|---|---|---|---|---|")
    for _, r in comp.iterrows():
        L.append(f"| {r['quantity']} | {r['primary']} | {r['sensitivity']} | {r['changed']} | {r['detail']} |")
    L.append("\n## Conclusion\n")
    L.append(("No headline result changes (superfamily direction/significance, matched reanalysis, classifications): "
              "TRACE_LBD fragments do not drive the functional-site conclusions. The primary analysis is kept; "
              "this exclusion is reported as a sensitivity result.") if material == 0 else
             f"{material} headline quantities change: the primary policy needs review before any change.")
    (PROJECT_ROOT / "reports" / "rebuild_v2" / "trace_lbd_site_sensitivity.md").write_text("\n".join(L) + "\n")
    print(comp.to_string(index=False))
    print(f"material headline changes: {material}")


if __name__ == "__main__":
    main()
