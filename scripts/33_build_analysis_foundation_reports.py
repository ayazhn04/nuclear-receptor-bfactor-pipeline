def build_missingness_report(master, inst, rec_prof, summ, norm_cols) -> str:
    coord = master[master["has_stage3b_coordinate_data"]]
    reps = inst[inst["is_representative_instance"]]
    norm_ok = inst["normalization_status"].eq("NORMALIZED")
    rep_ok = reps["normalization_status"].eq("NORMALIZED")

    lines = ["# Analysis Foundation — Coverage / Missingness Report", ""]
    lines += [
        "Generated by `scripts/33_build_analysis_foundation_reports.py` from the outputs of "
        "`scripts/32_build_normalization_foundation.py`. **Descriptive only. No structure or receptor is excluded; "
        "low-N receptors are flagged, never dropped. QC thresholds remain metadata.**", "",
        "## 1. Counts", "",
        f"- Master candidates (`structures.csv`): **{len(master)}** (all retained)",
        f"- Candidates with Stage 3B coordinate data: **{len(coord)}**; without: **{len(master) - len(coord)}** (retained, ligand/B fields not assessable)",
        f"- Coordinate instance/models: **{len(inst)}**",
        f"- Representative instances (one per coordinate candidate): **{len(reps)}**",
        f"- Normalizable instances: **{int(norm_ok.sum())}** of {len(inst)}; normalizable representative instances: **{int(rep_ok.sum())}** of {len(reps)}",
        f"- Non-normalizable instances (retained, z left missing): "
        + (", ".join(f"`{r.instance_id}` ({r.normalization_status}, {r.n_ca_usable} usable B)" for r in inst[~norm_ok].itertuples()) or "none"),
        f"- Unique PDB entries with a normalizable representative: **{inst[inst['is_representative_instance'] & norm_ok]['pdb_id'].nunique()}**",
        "",
        "## 2. Missing-residue distribution (standardized-LBD rows without a usable raw Ca B-factor)", "",
    ]
    qs = [0, 0.05, 0.25, 0.5, 0.75, 0.95, 1.0]
    dist = pd.DataFrame(
        {
            "instances": ["all instances", "representative instances"],
            **{f"q{int(q * 100)} missing rows": [inst["n_ca_missing"].quantile(q), reps["n_ca_missing"].quantile(q)] for q in qs},
        }
    )
    lines += [md_table(dist, "{:.1f}"), ""]
    bins = [-0.001, 0.5, 0.8, 0.9, 0.95, 0.99, 1.0001]
    labels = ["<0.50", "0.50-0.80", "0.80-0.90", "0.90-0.95", "0.95-0.99", ">=0.99"]
    hist = pd.DataFrame(
        {
            "usable_fraction bin": labels,
            "all instances": pd.cut(inst["usable_fraction"], bins, labels=labels).value_counts().reindex(labels).values,
            "representative instances": pd.cut(reps["usable_fraction"], bins, labels=labels).value_counts().reindex(labels).values,
        }
    )
    lines += ["`usable_fraction` = usable Ca B-factor rows / standardized-LBD length.", "", md_table(hist), ""]

    rr = norm_cols[norm_cols["is_representative_instance"]]
    unmapped = int((~rr["is_construct_mapped"]).sum())
    mapped_unobs = int((rr["is_construct_mapped"] & ~rr["ca_positive_occupancy"]).sum())
    zero_occ = int((rr["zero_occupancy_only_ca"]).sum())
    obs_no_b = int((rr["ca_positive_occupancy"] & ~rr["ca_bfactor_usable"]).sum())
    lines += [
        "Why residues lack a usable B (representative instances, all standardized-LBD rows = "
        f"{len(rr)}): construct does not map to the position **{unmapped}**; mapped but no occupancy>0 Ca **{mapped_unobs}** "
        f"(of which zero-occupancy-only placeholders: {zero_occ}); occupancy>0 but non-finite B **{obs_no_b}**. "
        "These rows are preserved explicitly in `lbd_residue_bfactors_all.parquet` and `normalized_lbd_bfactors_all.parquet`.", "",
    ]

    lines += ["## 3. Receptor-level counts, coverage and APO/HOLO balance (all 48 receptors)", ""]
    s = summ.copy()
    s["balance_flag"] = np.where(
        s["n_normalizable_pdbs"] == 0, "NO_DATA",
        np.where((s["apo_pdb_count"] < MIN_STATE_N_FOR_TESTING) | (s["holo_pdb_count"] < MIN_STATE_N_FOR_TESTING),
                 "INSUFFICIENT_APO_HOLO_BALANCE", "ADEQUATE_FOR_LATER_TESTING"),
    )
    t = s[["common_name", "nr_code", "n_master_candidates", "n_coordinate_candidates", "n_normalizable_pdbs",
           "median_lbd_observation_fraction", "apo_pdb_count", "holo_pdb_count", "ambiguous_pdb_count",
           "profile_status", "balance_flag"]]
    lines += [md_table(t), ""]
    lines += [
        f"Balance flag rule (descriptive, used only to flag later tests): a receptor is `INSUFFICIENT_APO_HOLO_BALANCE` "
        f"if fewer than {MIN_STATE_N_FOR_TESTING} PDB entries are APO **or** fewer than {MIN_STATE_N_FOR_TESTING} are HOLO. "
        "AMBIGUOUS and not-assessable states are never assigned to either group. No receptor is excluded.", "",
    ]
    insuff = s[s["balance_flag"] == "INSUFFICIENT_APO_HOLO_BALANCE"]
    lines += [f"Receptors with data but insufficient APO/HOLO balance ({len(insuff)}): "
              + ", ".join(f"{r.common_name} (APO {r.apo_pdb_count}/HOLO {r.holo_pdb_count})" for r in insuff.itertuples()), ""]
    nodata = s[s["balance_flag"] == "NO_DATA"]
    lines += [f"Receptors with no normalizable structures ({len(nodata)}): "
              + ", ".join(f"{r.common_name} [{r.profile_status}]" for r in nodata.itertuples()), ""]

    lines += ["## 4. Receptor positions supported by multiple PDB entries", ""]
    sup = summ[["common_name", "n_normalizable_pdbs", "n_positions_with_observation",
                "n_positions_ge3_pdbs", "n_positions_ge5_pdbs", "n_positions_ge10_pdbs"]].copy()
    sup.columns = ["receptor", "PDBs", "positions >=1 PDB", "positions >=3 PDBs", "positions >=5 PDBs", "positions >=10 PDBs"]
    tot = {"receptor": "**ALL (receptor-positions)**", "PDBs": int(summ["n_normalizable_pdbs"].sum())}
    for c in sup.columns[2:]:
        tot[c] = int(sup[c].sum())
    sup = pd.concat([sup, pd.DataFrame([tot])], ignore_index=True)
    lines += [md_table(sup), ""]
    lines += [
        "Support counts use PDB-level observations (one per receptor x PDB x position; multiple retained candidates in the same "
        "PDB are reduced by median), so duplicate chains/entities cannot inflate them.", "",
    ]
    return "\n".join(lines)


