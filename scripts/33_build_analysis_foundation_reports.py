def build_resolution_diagnostic(inst: pd.DataFrame) -> pd.DataFrame:
    reps = inst[inst["is_representative_instance"] & (inst["n_ca_usable"] >= 1)].copy()
    reps["resolution"] = pd.to_numeric(reps["resolution"], errors="coerce")
    note = ("Descriptive QC only. Raw B-factor summaries are resolution/refinement dependent and are NOT used directly for "
            "cross-structure biological comparison; this diagnostic never alters per-instance Z-scores. Rows with missing "
            "resolution are omitted from the pair only (structure stays in the master).")
    rows = []

    def add(scope, df):
        for ycol, label in [("raw_b_mean", "representative_raw_b_mean"), ("raw_b_median", "representative_raw_b_median")]:
            d = df[["resolution", ycol]].dropna()
            n = len(d)
            if n >= 3 and d["resolution"].nunique() > 1 and d[ycol].nunique() > 1:
                pr, pp = stats.pearsonr(d["resolution"], d[ycol])
                sr, sp = stats.spearmanr(d["resolution"], d[ycol])
            else:
                pr = pp = sr = sp = np.nan
            rows.append({"scope": scope, "x": "resolution_angstrom", "y": label, "n_pairs": n,
                         "pearson_r": pr, "pearson_p": pp, "spearman_rho": sr, "spearman_p": sp, "note": note})

    add("all_representative_coordinate_instances", reps)
    add("previous_strict_qc_subset_only", reps[reps["previous_primary_qc_member"].astype(bool)])
    add("outside_previous_strict_qc_subset", reps[~reps["previous_primary_qc_member"].astype(bool)])
    for name, g in reps.groupby("common_name"):
        if g["resolution"].notna().sum() >= 10:
            add(f"receptor:{name}", g)
    out = pd.DataFrame(rows)
    out["n_missing_resolution_omitted"] = 0
    tot_missing = int(reps["resolution"].isna().sum())
    out.loc[out["scope"] == "all_representative_coordinate_instances", "n_missing_resolution_omitted"] = tot_missing
    return out


