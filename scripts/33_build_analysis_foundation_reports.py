def lbd_sequences(norm_cols: pd.DataFrame) -> dict[str, dict[int, str]]:
    d = norm_cols.drop_duplicates(["uniprot_id", "canonical_uniprot_position"])
    seqs: dict[str, dict[int, str]] = {}
    for u, g in d.groupby("uniprot_id"):
        seqs[u] = {int(p): THREE_TO_ONE.get(n, "X") for p, n in zip(g["canonical_uniprot_position"], g["canonical_residue_name"])}
    return seqs


def build_alignment_report(lbd: pd.DataFrame, norm_cols: pd.DataFrame) -> str:
    seqs = lbd_sequences(norm_cols)
    L = ["# Common NR-LBD Alignment Readiness Audit", "",
         "**Decision point for professor review. No cross-receptor alignment, feature matrix, PCA, clustering or modelling has been built.** "
         "Generated by `scripts/33_build_analysis_foundation_reports.py`.", ""]

    L += ["## 1. Standardized LBD interval for all 48 receptors (UniProt canonical, 1-based, inclusive)", ""]
    t = lbd[["common_name", "nr_code", "group", "uniprot_id", "lbd_start", "lbd_end", "lbd_length"]].copy()
    L += [md_table(t), ""]
    ln = lbd["lbd_length"]
    L += ["## 2. Standardized LBD length distribution", "",
          f"n = {len(ln)}; min {ln.min()}, q25 {ln.quantile(.25):.1f}, median {ln.median():.1f}, q75 {ln.quantile(.75):.1f}, "
          f"max {ln.max()}; mean {ln.mean():.1f}; SD {ln.std(ddof=0):.1f}; number of distinct lengths {ln.nunique()}. "
          "Lengths differ between receptors, so relative index (position - start + 1) is not a common coordinate either.", ""]
    bins = pd.cut(ln, [0, 200, 220, 240, 260, 300, 1000]).value_counts().sort_index()
    L += [md_table(pd.DataFrame({"length bin": [str(i) for i in bins.index], "receptors": bins.values})), ""]

    # ---- integer-overlap analysis ----
    L += ["## 3. Are identical UniProt residue numbers across receptors homologous?", "",
          "**No.** `canonical_uniprot_position` is a receptor-specific coordinate: each receptor's numbering starts at its own "
          "N-terminus, and NR N-terminal regions differ enormously in length. Pivoting integer positions across receptors would "
          "line up non-homologous residues. Evidence from this repository's own data:", ""]
    ov_rows = []
    pairs = list(itertools.combinations(lbd.itertuples(), 2))
    no_overlap = 0
    for a, b in pairs:
        lo, hi = max(a.lbd_start, b.lbd_start), min(a.lbd_end, b.lbd_end)
        if hi < lo:
            no_overlap += 1
    L += [f"- Of {len(pairs)} receptor pairs, **{no_overlap} ({100 * no_overlap / len(pairs):.1f}%) have completely non-overlapping standardized-LBD "
          "UniProt integer ranges** — the same integer never falls inside both LBDs.",
          f"- LBD start positions range from {lbd['lbd_start'].min()} to {lbd['lbd_start'].max()} (median {lbd['lbd_start'].median():.0f}).", ""]

    ex_pos = 350
    ex = lbd[["common_name", "lbd_start", "lbd_end"]].copy()
    ex["in_LBD_at_350"] = (ex["lbd_start"] <= ex_pos) & (ex_pos <= ex["lbd_end"])
    ex["relative_index_of_350"] = np.where(ex["in_LBD_at_350"], ex_pos - ex["lbd_start"] + 1, np.nan)
    ex["residue_at_350"] = [seqs.get(u, {}).get(ex_pos, "") for u in lbd["uniprot_id"]]
    ex = ex[ex["in_LBD_at_350"]].drop(columns="in_LBD_at_350")
    L += [f"Example: UniProt position {ex_pos} lies inside the standardized LBD of {len(ex)} of 48 receptors, but at very different "
          "relative positions within the domain (`relative_index_of_350`), so it is a different structural element in each:", "",
          md_table(ex.head(15), "{:.0f}"), ""]

    have = [u for u in lbd["uniprot_id"] if u in seqs and len(seqs[u]) == int(lbd.set_index('uniprot_id').loc[u, 'lbd_length'])]
    L += [f"### Naive identity at identical positions (reconstructed from the {len(have)} receptors with coordinate-derived LBD residue names)", ""]
    lb = lbd.set_index("uniprot_id")
    int_ids, rel_ids, comp = [], [], []
    for u, v in itertools.combinations(have, 2):
        su, sv = seqs[u], seqs[v]
        common = set(su) & set(sv)
        if common:
            int_ids.append(np.mean([su[p] == sv[p] for p in common]))
        m = min(len(su), len(sv))
        ru = [su[lb.loc[u, "lbd_start"] + i] for i in range(m)]
        rv = [sv[lb.loc[v, "lbd_start"] + i] for i in range(m)]
        rel_ids.append(np.mean([x == y for x, y in zip(ru, rv)]))
    allres = pd.Series([a for u in have for a in seqs[u].values()]).value_counts(normalize=True)
    chance = float((allres ** 2).sum())
    L += [f"- Mean identity when residues are matched by identical UniProt integer (pairs with any integer overlap: {len(int_ids)}): **{np.mean(int_ids):.3f}**",
          f"- Mean identity when matched by relative LBD index (first m residues of each LBD): **{np.mean(rel_ids):.3f}**",
          f"- Expected identity of two random residues drawn from the pooled NR-LBD composition: **{chance:.3f}**", "",
          "Both naive schemes sit close to chance, i.e. they behave like random residue pairings rather than homologous ones.", ""]

    # ---- pairwise alignment illustration (not an MSA) ----
    try:
        from Bio import Align
        from Bio.Align import substitution_matrices

        al = Align.PairwiseAligner()
        al.substitution_matrix = substitution_matrices.load("BLOSUM62")
        al.open_gap_score, al.extend_gap_score = -10, -0.5
        al.mode = "global"
        L += ["### Illustration: a pairwise alignment reorders the mapping (Biopython `PairwiseAligner`, BLOSUM62; illustrative only, NOT an MSA)", ""]
        rows = []
        name2u = dict(zip(lbd["common_name"], lbd["uniprot_id"]))
        for a, b in [("ERα", "ERβ"), ("ERα", "PPARγ"), ("PPARγ", "RXRα"), ("VDR", "TRβ")]:
            ua, ub = name2u.get(a), name2u.get(b)
            if ua not in seqs or ub not in seqs:
                continue
            sa = "".join(seqs[ua][p] for p in sorted(seqs[ua]))
            sb = "".join(seqs[ub][p] for p in sorted(seqs[ub]))
            aln = al.align(sa, sb)[0]
            ia = ib = matches = aligned = 0
            for (a0, a1), (b0, b1) in zip(*aln.aligned):
                for k in range(a1 - a0):
                    aligned += 1
                    matches += sa[a0 + k] == sb[b0 + k]
            offsets = [b0 - a0 for (a0, a1), (b0, b1) in zip(*aln.aligned)]
            rows.append({"pair": f"{a} vs {b}", "aligned_pairs": aligned, "identity_in_alignment": matches / aligned,
                         "relative_index_offsets_range": f"{min(offsets)}..{max(offsets)}"})
        if rows:
            L += [md_table(pd.DataFrame(rows)), "",
                  "Aligned identity is far above the naive-index identity above, and the offset between receptors' relative indices "
                  "is not constant (gaps), so a real alignment coordinate is required.", ""]
    except Exception as exc:  # pragma: no cover
        L += [f"(Pairwise illustration unavailable: {exc})", ""]

    # ---- repository check ----
    L += ["## 4. Does the repository already contain a common multi-receptor alignment coordinate?", ""]
    hits = []
    for f in sorted(list(MANIFESTS.glob("*.csv")) + list(PROCESSED.glob("*.csv")) + list(ANALYSIS.glob("*.csv"))):
        for c in pd.read_csv(f, nrows=0).columns:
            if any(k in c.lower() for k in ["msa", "align_pos", "alignment_col", "hmm", "pfam", "common_pos", "match_state"]):
                hits.append(f"`{f.relative_to(PROJECT_ROOT)}`:`{c}`")
    L += [f"- Column-name scan of all tracked CSV manifests/tables for MSA/HMM/common-position style columns: **{'none found' if not hits else ', '.join(hits)}**.",
          "- `data/manifests/nr_lbd_reference.csv` provides only per-receptor UniProt intervals (PROSITE PS51843 / PRU01189-backed), not a shared coordinate.",
          "- `data/manifests/rcsb_sequence_coordinate_alignments.csv` maps UniProt <-> PDB entity residues within one receptor; it is not a receptor-to-receptor alignment.",
          "- **Conclusion: no common multi-receptor alignment coordinate exists yet.**", ""]

    L += ["## 5. Alignment software available in this environment", ""]
    tools = ["mafft", "muscle", "clustalo", "clustalw2", "hmmalign", "hmmbuild", "kalign", "t_coffee", "famsa"]
    L += [md_table(pd.DataFrame({"tool": tools, "on PATH": ["found: " + shutil.which(t) if shutil.which(t) else "not found" for t in tools]})), ""]
    mods = ["pyhmmer", "skbio", "parasail", "sklearn", "statsmodels"]
    L += [md_table(pd.DataFrame({"python module": mods, "importable": [importlib.util.find_spec(m) is not None for m in mods]})), "",
          "Biopython (`Bio.Align.PairwiseAligner`, substitution matrices) is available and was used above for pairwise illustration only; "
          "it does not provide a multiple-sequence alignment. **No MSA/HMM program is installed, and none was installed by this stage.**", ""]

    L += ["## 6. Recommended reproducible approach (needs professor confirmation and permission to add software)", "",
          "Goal: a deterministic table `uniprot_id, canonical_uniprot_position -> common_lbd_position (or NULL for insertions)`.", "",
          "1. **Primary (recommended): profile-HMM coordinate.** Align each standardized LBD sequence to the Pfam Hormone_recep (PF00104) "
          "profile HMM with `hmmalign` (HMMER); the HMM match-state index is the common coordinate. It is anchored to a fixed, versioned "
          "external reference, is order-independent, and new receptors can be added without re-aligning the rest. Record the Pfam/HMMER "
          "versions and the HMM file checksum. The repository already uses the same domain evidence (PROSITE PS51843; Pfam PF00104 "
          "was cross-referenced in the LBD definition stages).",
          "2. **Cross-check: MAFFT (L-INS-i) MSA of the 48 standardized LBD sequences** from the pinned UniProt canonical sequences; "
          "columns define a second coordinate. Pin the version, command line and input FASTA checksum.",
          "3. **Optional structural check:** compare the sequence-derived columns against a structure-based alignment of representative "
          "structures (e.g. conserved helix boundaries H1-H12) to validate the placement of the AF-2 helix and loops.",
          "4. Deliverables to be tracked: input FASTA, alignment file, tool versions/commands, and the "
          "position-mapping CSV keyed by (uniprot_id, canonical_uniprot_position). Positions in insertions relative to the reference get "
          "NULL rather than being forced into a column; each receptor x common-position cell keeps a missing-value reason.",
          "5. Only after the mapping is approved: pivot `receptor_position_flexibility_profiles.parquet` onto common positions, "
          "and only then consider any cross-receptor modelling.", "",
          "**Requested decisions:** (a) approve HMM (PF00104) vs MSA vs structure-based coordinate as the definition of 'common position'; "
          "(b) permission to install HMMER and/or MAFFT (nothing was installed here); (c) how to treat receptor-specific insertions "
          "(drop, or keep as receptor-private columns); (d) minimum number of supporting PDBs per receptor-position for downstream use.", ""]
    return "\n".join(L)


def main() -> None:
    master = pd.read_csv(PROCESSED / "structures.csv", dtype={"pdb_id": str})
    inst = pd.read_csv(ANALYSIS / "instance_bfactor_summary.csv", dtype={"pdb_id": str})
    rec_prof = pd.read_parquet(ANALYSIS / "receptor_position_flexibility_profiles.parquet")
    summ = pd.read_csv(ANALYSIS / "receptor_flexibility_summary.csv")
    lbd = pd.read_csv(MANIFESTS / "nr_lbd_reference.csv")
    norm_cols = pd.read_parquet(
        ANALYSIS / "normalized_lbd_bfactors_all.parquet",
        columns=["uniprot_id", "instance_id", "canonical_uniprot_position", "canonical_residue_name", "is_representative_instance",
                 "is_construct_mapped", "ca_positive_occupancy", "ca_bfactor_usable", "zero_occupancy_only_ca"],
    )
    TABLES.mkdir(parents=True, exist_ok=True)
    MISSINGNESS_MD.write_text(build_missingness_report(master, inst, rec_prof, summ, norm_cols) + "\n")
    print(f"wrote {MISSINGNESS_MD.relative_to(PROJECT_ROOT)}")
    diag = build_resolution_diagnostic(inst)
    diag.to_csv(RESOLUTION_CSV, index=False)
    print(f"wrote {RESOLUTION_CSV.relative_to(PROJECT_ROOT)} ({len(diag)} rows)")
    ALIGNMENT_MD.write_text(build_alignment_report(lbd, norm_cols) + "\n")
    print(f"wrote {ALIGNMENT_MD.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
